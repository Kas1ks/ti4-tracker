export const secretObjectiveById = new Map(
  SECRET_OBJECTIVES.map((card) => [card.id, card]),
);

/** Active secret deck for the current expansion setup. */
export function secretDeckForExp({ pok = false } = {}) {
  return SECRET_OBJECTIVES.filter((card) => card.exp === 'base' || (pok && card.exp === 'pok'));
}

export function secretObjectivePhaseLabel(phase) {
  if (phase === 'action') return 'Действие';
  if (phase === 'agenda') return 'Политика';
  return 'Статус';
}
