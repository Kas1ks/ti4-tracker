export const agendaById = new Map(AGENDA_CARDS.map((c) => [c.id, c]));

/** Active deck for a table setup. PoK removes base cards marked removedByPok. */
export function agendaDeckForExp({ pok = false } = {}) {
  return AGENDA_CARDS.filter((c) => {
    if (c.exp === 'pok') return !!pok;
    if (pok && c.removedByPok) return false;
    return true;
  });
}

export function agendaVoteType(cardOrId) {
  const card = typeof cardOrId === 'string' ? agendaById.get(cardOrId) : cardOrId;
  return card?.voteType || 'OTHER';
}

/** Localized effect blurb for UI (defaults to Russian). */
export function agendaEffectText(cardOrId, { lang = 'ru' } = {}) {
  const card = typeof cardOrId === 'string' ? agendaById.get(cardOrId) : cardOrId;
  if (!card) return '';
  const en = lang === 'en';
  if (card.voteType === 'FOR_AGAINST') {
    const forT = en ? card.forTextEn : card.forText;
    const againstT = en ? card.againstTextEn : card.againstText;
    const parts = [];
    if (forT) parts.push(en ? `For: ${forT}` : `За: ${forT}`);
    if (againstT) parts.push(en ? `Against: ${againstT}` : `Против: ${againstT}`);
    if (card.text || card.textEn) {
      parts.unshift(en ? (card.textEn || card.text) : (card.text || card.textEn));
    }
    return parts.join('\n\n');
  }
  return en ? (card.textEn || card.text || '') : (card.text || card.textEn || '');
}

