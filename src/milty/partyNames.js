/** Fix accidental space typos in static lists if any slipped in. */
function clean(s) {
  return String(s).replace(/\s+/g, ' ').trim();
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

const recent = [];
const RECENT_CAP = 12;

function remember(name) {
  recent.push(name);
  if (recent.length > RECENT_CAP) recent.shift();
}

function uniqueEnough(candidate) {
  return !recent.includes(candidate);
}

function buildOnce() {
  const roll = Math.random();
  if (roll < 0.28) return clean(pick(EPICS));
  if (roll < 0.55) {
    const [adj, noun] = pick(ADJECTIVE_NOUNS);
    return clean(`${adj} ${noun}`);
  }
  if (roll < 0.78) return clean(`${pick(OPENERS)} ${pick(TAILS)}`);
  // Short genitive-style: opener + place-like epic fragment
  return clean(`${pick(OPENERS)} ${pick([
    'Империи',
    'совета',
    'пустоты',
    'трона',
    'флота',
    'червоточины',
    'Рекса',
    'Иксита',
    'горизонта',
    'бастиона',
    'короны',
    'протокола',
    'туманности',
    'рубежа',
    'галактики',
  ])}`);
}

/**
 * Generate a random party / draft display name.
 * @returns {string}
 */
export function randomPartyName() {
  let name = buildOnce();
  for (let i = 0; i < 6 && !uniqueEnough(name); i += 1) {
    name = buildOnce();
  }
  remember(name);
  return name;
}
